// The interface's language: English (as the code is written), Modern Greek (el) or
// Ancient Greek (grc), as the text menu (Aa, theme.js) chooses; remembered per browser.
// The texts stay as they are: only the interface around them is translated.
//
// tr("Day {n}", {n: 3}) gives a phrase in the language chosen, its {names} filled in; the
// pages' own HTML is translated as it loads (translatePage), its text and its titles,
// labels and placeholders, where they are phrases below. A phrase not translated stays
// in English.
// Ancient Greek isn't offered yet but on a local server (its wording still to be checked).
const GRC_READY = ["localhost", "127.0.0.1"].includes(location.hostname);
let UI_LANG = "en";
try {
  const l = localStorage.getItem("uiLang");
  if (l === "el" || (l === "grc" && GRC_READY)) UI_LANG = l;
} catch {}
// Dates and numbers (Intl has no Ancient Greek: Modern Greek's will do).
const UI_LOCALE = UI_LANG === "en" ? undefined : "el";
document.documentElement.dataset.ui = UI_LANG;  // (for the stylesheet: Greek labels are longer)

function tr(phrase, vars) {
  let out = I18N[UI_LANG]?.[phrase] ?? phrase;
  if (vars) out = out.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
  return out;
}

// The page's HTML: its text (a phrase alone in its element, as the HTML has it) and its
// titles, labels and placeholders. Not the language buttons, each in its own language.
function translatePage(root = document.body) {
  if (UI_LANG === "en") return;
  const words = I18N[UI_LANG];
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  for (let n = walker.nextNode(); n; n = walker.nextNode()) {
    const s = n.nodeValue.trim();
    if (s && words[s] && !n.parentElement.closest(".lang-choice")) n.nodeValue = n.nodeValue.replace(s, words[s]);
  }
  for (const el of root.querySelectorAll("[title], [aria-label], [placeholder]")) {
    if (el.closest(".lang-choice")) continue;
    for (const a of ["title", "aria-label", "placeholder"]) {
      const v = el.getAttribute(a);
      if (v && words[v]) el.setAttribute(a, words[v]);
    }
  }
  if (words[document.title]) document.title = words[document.title];
  // (English said beside Greek, as the library's "Acroaterium" under Ἀκροατήριον: not needed)
  for (const el of root.querySelectorAll("[data-en-only]")) el.hidden = true;
}

// A heading in capitals, as Greek is written in capitals: without its accents, breathings
// and iota subscript (Η ΑΓΙΑ ΓΡΑΦΗ). The library's headings, and the interface's labels
// set in capitals (a style's uppercase keeps the accents: ΡΌΛΟΣ).
function capitals(text) {
  return text.normalize("NFD").replace(/[\u0300\u0301\u0313\u0314\u0342\u0345]/g, "").normalize("NFC").toUpperCase();
}

